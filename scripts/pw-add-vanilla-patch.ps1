#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Create a paperweight-compatible MODIFICATION patch for a vanilla class that
    only exists in mc-dev-sources (i.e. is not part of the src tree / upstream).

.DESCRIPTION
    paperweight's applyPatches flow (ApplyPaperPatches.kt):
        clone upstream -> copy remapped sources -> McDev.importMcDev(patches=...)
        -> commit "Initial", tag it "base" -> git am --3way <all patches>

    importMcDev scans every patch for lines starting with
        +++ b/src/main/java/
    and, for each such path that does NOT exist in the target dir, copies the
    vanilla decompiled file in.

    Consequence for vanilla-only classes:
      * "new file" patch  -> vanilla is imported first -> "both added" conflict
      * "modification"    -> vanilla is imported first -> applies cleanly

    rebuildPatches runs `git format-patch base..HEAD`, and base already contains
    the imported vanilla files. So once a file has been introduced through a
    patch generated by this script, it behaves like any normal file: just edit it
    in the work tree, commit, and run rebuildPatches.

    This script only handles the FIRST introduction of such a file.

.PARAMETER Path
    Class path relative to src/main/java, e.g.
    net/minecraft/world/effect/MobEffects.java

.PARAMETER ModifiedFile
    File containing the edited content (usually your edited copy of the cache file).

.PARAMETER Subject
    Commit subject; used for the patch subject and file name.

.EXAMPLE
    ./scripts/pw-add-vanilla-patch.ps1 `
        -Path net/minecraft/world/effect/MobEffects.java `
        -ModifiedFile ./.dsh-work/MobEffects.java `
        -Subject "Custom weakness tuning"
#>
param(
    [Parameter(Mandatory = $true)][string]$Path,
    [Parameter(Mandatory = $true)][string]$ModifiedFile,
    [Parameter(Mandatory = $true)][string]$Subject,
    [string]$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path,
    [string]$ServerDir = 'Purpur-Server',
    [string]$PatchDir = 'patches/server'
)

$ErrorActionPreference = 'Stop'
$serverPath = Join-Path $RepoRoot $ServerDir
$patchPath = Join-Path $RepoRoot $PatchDir
$cacheRoot = Join-Path $serverPath '.gradle/caches/paperweight/mc-dev-sources'
$rel = $Path -replace '\\', '/'
$repoRel = "src/main/java/$rel"

if (-not (Test-Path $patchPath)) { throw "patch dir not found: $patchPath" }
if (-not (Test-Path $ModifiedFile)) { throw "modified file not found: $ModifiedFile" }

function Read-Lf([string]$p) {
    ([System.IO.File]::ReadAllText($p)) -replace "`r`n", "`n"
}

# ---------- 1. locate the vanilla content ----------
$cacheFile = Join-Path $cacheRoot ($rel -replace '/', '\')
$scratch = Join-Path $RepoRoot '.dsh-scratch'
$aux = Join-Path $RepoRoot '.dsh-scratch-tmp'

if (Test-Path $cacheFile) {
    $vanilla = Read-Lf $cacheFile
    $vanillaFrom = 'mc-dev-sources cache'
} else {
    Remove-Item $aux -Recurse -Force -ErrorAction SilentlyContinue
    New-Item -ItemType Directory -Force -Path $aux | Out-Null
    $tmp = Join-Path $aux 'vanilla.tmp'
    cmd /c "git -C `"$serverPath`" cat-file blob base:$repoRel > `"$tmp`" 2>nul"
    if (-not (Test-Path $tmp) -or (Get-Item $tmp).Length -eq 0) {
        throw "not in cache and not in 'base' commit: $rel (if it is not a vanilla class, use a normal commit + rebuildPatches)"
    }
    $vanilla = Read-Lf $tmp
    $vanillaFrom = "'base' commit"
}

$modified = Read-Lf (Resolve-Path $ModifiedFile)
if ($vanilla -ceq $modified) { throw "modified content is identical to vanilla; nothing to patch" }

# ---------- 2. build the "vanilla -> modified" diff in a throwaway repo ----------
Remove-Item $scratch -Recurse -Force -ErrorAction SilentlyContinue
Remove-Item $aux -Recurse -Force -ErrorAction SilentlyContinue
$workFile = Join-Path $scratch ($repoRel -replace '/', '\')
New-Item -ItemType Directory -Force -Path (Split-Path $workFile) | Out-Null
New-Item -ItemType Directory -Force -Path $aux | Out-Null

function Invoke-Git {
    param([string[]]$GitArgs)
    & git -C $scratch -c user.name=Prism -c user.email=prism@localhost -c core.autocrlf=false @GitArgs
    if ($LASTEXITCODE -ne 0) { throw "git failed ($LASTEXITCODE): $($GitArgs -join ' ')" }
}

Invoke-Git @('init', '-q')
[System.IO.File]::WriteAllText($workFile, $vanilla)
Invoke-Git @('add', '-A')
Invoke-Git @('commit', '-q', '-m', 'vanilla')

[System.IO.File]::WriteAllText($workFile, $modified)
Invoke-Git @('add', '-A')
Invoke-Git @('commit', '-q', '-m', $Subject)

$outDir = Join-Path $aux 'out'
Invoke-Git @('format-patch', '-1', 'HEAD', '--zero-commit', '--full-index', '--no-signature', '--no-stat', '-o', $outDir)
$generated = Get-ChildItem $outDir -Filter '*.patch' | Select-Object -First 1
if (-not $generated) { throw 'format-patch produced no file' }

$body = Get-Content $generated.FullName -Raw
if ($body -match 'new file mode') { throw 'generated a NEW FILE patch; the pre-image did not take effect' }
if (-not ($body -match [regex]::Escape("+++ b/$repoRel"))) {
    throw "patch has no '+++ b/$repoRel' line; importMcDev will not import the vanilla file"
}

# ---------- 3. append to the patch series ----------
$max = 0
Get-ChildItem $patchPath -Filter '*.patch' | ForEach-Object {
    if ($_.Name -match '^(\d{4})-') { $max = [Math]::Max($max, [int]$Matches[1]) }
}
$seq = $max + 1
$slug = ($Subject -replace '[^A-Za-z0-9]+', '-').Trim('-')
if ($slug.Length -gt 60) { $slug = $slug.Substring(0, 60).Trim('-') }
$target = Join-Path $patchPath ('{0:D4}-{1}.patch' -f $seq, $slug)
Copy-Item $generated.FullName $target -Force

Remove-Item $scratch -Recurse -Force -ErrorAction SilentlyContinue
Remove-Item $aux -Recurse -Force -ErrorAction SilentlyContinue
Write-Host ("vanilla source : {0}" -f $vanillaFrom)
Write-Host ("patch written  : {0}" -f ($target.Replace($RepoRoot + '\', '')))
Write-Host ("pre-image blob : {0}" -f ([regex]::Match($body, '^index ([0-9a-f]+)\.\.', 'Multiline').Groups[1].Value))
Write-Host ''
Write-Host 'next: ./gradlew applyPatches   (expect "N patches applied cleanly")'
